-- E-commerce platform. Timestamps are timestamptz (UTC).
-- Model: docs/architecture/source-systems.md, section 3.

\connect ecommerce
SET ROLE generator;  -- objects are owned by the application role, not the superuser

-- updated_at is maintained by the database on every UPDATE that changes the
-- row: it is the incremental cursor and cannot be forgotten by application code.
-- INSERTs keep the value provided (the historical load writes simulated dates).
CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TABLE customers (
    customer_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            varchar(255) NOT NULL,
    first_name       varchar(100) NOT NULL,
    last_name        varchar(100) NOT NULL,
    phone            varchar(30),
    crm_customer_ref varchar(20),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
-- Login email is unique regardless of case and surrounding spaces
CREATE UNIQUE INDEX customers_email_uk ON customers (lower(btrim(email)));

CREATE TABLE orders (
    order_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number          varchar(20) NOT NULL UNIQUE,
    customer_id           bigint REFERENCES customers (customer_id),
    guest_email           varchar(255),
    order_status          varchar(20) NOT NULL
        CHECK (order_status IN ('pending_payment', 'paid', 'shipped', 'delivered', 'cancelled')),
    order_ts              timestamptz NOT NULL,
    coupon_code           varchar(30),
    order_discount_amount numeric(12, 2) NOT NULL DEFAULT 0 CHECK (order_discount_amount >= 0),
    shipping_amount       numeric(12, 2) NOT NULL DEFAULT 0 CHECK (shipping_amount >= 0),
    ship_city             varchar(100) NOT NULL,
    ship_state            varchar(50)  NOT NULL,  -- no check: malformed values are intentional (Q12)
    ship_postal_code      varchar(10),
    cancelled_at          timestamptz,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    -- registered customer or guest checkout
    CHECK (customer_id IS NOT NULL OR guest_email IS NOT NULL)
);
CREATE INDEX orders_customer_id_idx ON orders (customer_id);
CREATE INDEX orders_updated_at_idx  ON orders (updated_at);

CREATE TABLE order_items (
    order_item_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             bigint   NOT NULL REFERENCES orders (order_id),
    line_number          smallint NOT NULL,
    sku                  varchar(30) NOT NULL,  -- logical ref to ERP, format varies (Q5, Q6)
    quantity             integer NOT NULL CHECK (quantity > 0),
    unit_price           numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
    item_discount_amount numeric(12, 2) NOT NULL DEFAULT 0 CHECK (item_discount_amount >= 0),
    tax_amount           numeric(12, 2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    UNIQUE (order_id, line_number)
);
CREATE INDEX order_items_updated_at_idx ON order_items (updated_at);

CREATE TABLE payments (
    payment_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                bigint   NOT NULL REFERENCES orders (order_id),
    attempt_number          smallint NOT NULL,
    payment_method          varchar(20) NOT NULL
        CHECK (payment_method IN ('credit_card', 'debit_card', 'paypal', 'gift_card')),
    payment_status          varchar(20) NOT NULL
        CHECK (payment_status IN ('authorized', 'captured', 'failed', 'refunded')),
    amount                  numeric(12, 2) NOT NULL,
    provider_transaction_id varchar(64) NOT NULL,  -- not unique: webhook retries duplicate rows (Q7)
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX payments_order_id_idx   ON payments (order_id);
CREATE INDEX payments_updated_at_idx ON payments (updated_at);

CREATE TABLE returns (
    return_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint NOT NULL REFERENCES orders (order_id),
    return_status varchar(20) NOT NULL
        CHECK (return_status IN ('requested', 'approved', 'received', 'refunded', 'rejected')),
    reason_code   varchar(30) NOT NULL,
    requested_at  timestamptz NOT NULL,
    refunded_at   timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CHECK (refunded_at IS NULL OR refunded_at >= requested_at)
);
CREATE INDEX returns_order_id_idx ON returns (order_id);

CREATE TABLE return_items (
    return_item_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id         bigint NOT NULL REFERENCES returns (return_id),
    order_item_id     bigint NOT NULL REFERENCES order_items (order_item_id),
    quantity_returned integer NOT NULL CHECK (quantity_returned > 0),
    refund_amount     numeric(12, 2) NOT NULL CHECK (refund_amount >= 0),  -- net of tax
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX return_items_return_id_idx     ON return_items (return_id);
CREATE INDEX return_items_order_item_id_idx ON return_items (order_item_id);

-- One trigger per table. "WHEN (OLD IS DISTINCT FROM NEW)" skips no-op updates,
-- so rewriting a row with identical values does not move the cursor.
CREATE TRIGGER customers_set_updated_at    BEFORE UPDATE ON customers
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER orders_set_updated_at       BEFORE UPDATE ON orders
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER order_items_set_updated_at  BEFORE UPDATE ON order_items
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER payments_set_updated_at     BEFORE UPDATE ON payments
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER returns_set_updated_at      BEFORE UPDATE ON returns
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER return_items_set_updated_at BEFORE UPDATE ON return_items
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();

RESET ROLE;
