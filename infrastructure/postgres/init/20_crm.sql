-- CRM. Timestamps are local time (America/New_York) WITHOUT time zone, on
-- purpose (Q8): the warehouse must standardize them.
-- Model: docs/architecture/source-systems.md, section 4.

\connect crm
SET ROLE generator;

CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now() AT TIME ZONE 'America/New_York';
    RETURN NEW;
END;
$$;

CREATE TABLE customers (
    crm_customer_id varchar(20) PRIMARY KEY,  -- CRM-0001234
    full_name       varchar(200) NOT NULL,
    segment         varchar(10)  NOT NULL CHECK (segment IN ('bronze', 'silver', 'gold', 'platinum')),
    status          varchar(10)  NOT NULL CHECK (status IN ('active', 'inactive')),
    is_deleted      boolean      NOT NULL DEFAULT false,  -- soft delete (Q11)
    created_at      timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York'),
    updated_at      timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York')
);
CREATE INDEX customers_updated_at_idx ON customers (updated_at);

CREATE TABLE customer_contacts (
    contact_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crm_customer_id varchar(20) NOT NULL REFERENCES customers (crm_customer_id),
    contact_type    varchar(10)  NOT NULL CHECK (contact_type IN ('email', 'phone')),
    contact_value   varchar(255) NOT NULL,  -- PII
    is_primary      boolean      NOT NULL DEFAULT false,
    created_at      timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York'),
    updated_at      timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York')
);
CREATE INDEX customer_contacts_customer_idx ON customer_contacts (crm_customer_id);
-- At most one primary contact per customer and type (partial unique index)
CREATE UNIQUE INDEX customer_contacts_one_primary_uk
    ON customer_contacts (crm_customer_id, contact_type) WHERE is_primary;

CREATE TRIGGER customers_set_updated_at         BEFORE UPDATE ON customers
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER customer_contacts_set_updated_at BEFORE UPDATE ON customer_contacts
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();

RESET ROLE;
