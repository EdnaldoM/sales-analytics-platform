-- ERP. Timestamps are local time (America/New_York) WITHOUT time zone (Q8).
-- Model: docs/architecture/source-systems.md, section 5.

\connect erp
SET ROLE generator;

CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now() AT TIME ZONE 'America/New_York';
    RETURN NEW;
END;
$$;

CREATE TABLE product_categories (
    category_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code      varchar(30)  NOT NULL UNIQUE,
    category_name      varchar(100) NOT NULL,
    parent_category_id integer REFERENCES product_categories (category_id),  -- null: top level
    created_at         timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York'),
    updated_at         timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York')
);

CREATE TABLE products (
    product_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          varchar(30)  NOT NULL UNIQUE,  -- canonical, uppercase
    product_name varchar(200) NOT NULL,
    category_id  integer NOT NULL REFERENCES product_categories (category_id),
    brand        varchar(100),
    list_price   numeric(10, 2) NOT NULL CHECK (list_price > 0),
    is_active    boolean NOT NULL DEFAULT true,
    created_at   timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York'),
    updated_at   timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York')
);
CREATE INDEX products_category_id_idx ON products (category_id);

CREATE TABLE product_cost_history (
    cost_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES products (product_id),
    unit_cost  numeric(10, 2) NOT NULL CHECK (unit_cost > 0),
    valid_from date NOT NULL,
    valid_to   date,  -- null: current cost
    created_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York'),
    updated_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'America/New_York'),
    CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE INDEX product_cost_history_product_idx ON product_cost_history (product_id);
-- Exactly one open (current) cost row per product
CREATE UNIQUE INDEX product_cost_history_one_open_uk
    ON product_cost_history (product_id) WHERE valid_to IS NULL;

CREATE TRIGGER product_categories_set_updated_at   BEFORE UPDATE ON product_categories
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER products_set_updated_at             BEFORE UPDATE ON products
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER product_cost_history_set_updated_at BEFORE UPDATE ON product_cost_history
    FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION set_updated_at();

RESET ROLE;
